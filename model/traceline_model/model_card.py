"""Generate MODEL_CARD.md from the report files so every number comes from a script."""
from __future__ import annotations

import json
from pathlib import Path


def load(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def main():
    res = load("reports/results.json")
    meta = load("model_meta.json")
    bench = load("reports/benchmark_python.json")
    browser = sorted(Path("reports").glob("benchmark_browser_*.json"))
    if res is None or meta is None:
        raise SystemExit("run `make eval export` first")
    acc = res["accuracy"]["overall"]
    methods = list(acc)
    best_base = min(("B1", "B2", "B3"), key=lambda m: acc[m]["mean"])
    nn = acc["Traceline"]
    wins = {k: nn[k] < acc[best_base][k] for k in ("median", "mean", "rmse", "p90", "p95")}
    L = []
    a = L.append
    a("# Traceline model card (Workstream B)")
    a("")
    a("> **All numbers below are generated by `python -m traceline_model.model_card` from `reports/*.json` and are measured on "
      "SYNTHETIC stand-in data (development split). They are not hidden-set results and not real-hardware results. "
      "Member C re-scores the headline numbers independently.**")
    a("")
    a("## Intended use")
    a("A positioning engine for a simulation and planning prototype: robust 2-D position, uncertainty, per-anchor blocked-reading "
      "probability, short motion forecast and a traceable explanation. Not a certified life-safety system.")
    a("")
    a("## Model")
    c = meta["model_config"]
    a(f"- Per-anchor shared encoder, per-anchor NLOS / reliability / bias heads, differentiable closed-form weighted multilateration, "
      f"GRUCell (hidden {c['hidden']}) for temporal fusion, heads for correction, sigma and a {c['horizon']}-step forecast.")
    a(f"- ONNX opset {meta['onnx_opset']}, {meta['model_size_bytes'] / 1024:.0f} KB. Inputs: 8 anchor slots "
      f"(x, y, range, rssi, valid_flag, crowd), previous position + validity, dt, recurrent state. Normalisation is train-only and lives in the graph.")
    a(f"- State: shape {meta['state']['shape']}; reset = {meta['state']['reset']}")
    a(f"- Crowd input enabled: **{meta['enable_crowd_input']}** (contract: optional, only if the team agrees).")
    a(f"- Uncertainty semantics: {meta['sigma_semantics']}")
    a(f"- `confidence` = {meta['confidence_definition']}")
    a("")
    a("## Data")
    a("Generated by `traceline_model/standin_data.py` from the guide's section 8 equations (range noise 0.15+0.02d, RSSI path loss with 2.5 dB noise, "
      "NLOS bias U(0.5,3.0) m, 5%+ packet loss, outages, outliers, drift, crowd effects). Venues: hospital, warehouse, office sketches (clinic is hidden-only and never built). "
      "**Temporary**: replace with Member A's datasets (same CSV contracts). Splits are by whole run; seeds 1000 (train) / 2000 (dev).")
    a(f"Dev set: {res['dev_runs']} runs, {res['dev_steps']} steps.")
    a("")
    a("## Position error on dev (m)")
    a("")
    a("| Method | median | mean | RMSE | P90 | P95 |")
    a("|---|---|---|---|---|---|")
    for m in methods:
        s = acc[m]
        a(f"| {m} | {s['median']:.2f} | {s['mean']:.2f} | {s['rmse']:.2f} | {s['p90']:.2f} | {s['p95']:.2f} |")
    a("")
    better = [k for k, v in wins.items() if v]
    worse = [k for k, v in wins.items() if not v]
    a(f"Against the strongest classical baseline on mean error ({best_base}), Traceline is better on {', '.join(better) or 'no metric'}"
      f"{' and not better on ' + ', '.join(worse) if worse else ''}. Baselines were tuned on a train subset only: {res['baseline_params']}.")
    a("See `reports/summary.md` for slices by venue, active-anchor count, NLOS presence and fewer-than-3-valid-anchor steps.")
    a("")
    n = res["nlos"]
    a("## Blocked-reading (NLOS) detection")
    a(f"Threshold {n['threshold']:.2f} (selected on even dev runs, reported on odd dev runs): precision {n['precision']:.3f}, recall {n['recall']:.3f}, "
      f"F1 {n['f1']:.3f}; confusion {n['confusion']}; positive rate {n['positive_rate_in_reported_runs']:.2f}.")
    a("")
    a("## Uncertainty calibration")
    for cv in res["calibration"]["coverage"]:
        a(f"- Radial error within {cv['k']:.0f} sigma: observed {cv['empirical']:.3f}, nominal {cv['nominal']:.3f}")
    a("Observed vs nominal gaps mean sigma is not perfectly calibrated; see `reports/calibration.png`. Calibrate on dev before relying on it.")
    a("")
    a("## Ablations (dev, overall)")
    a("")
    a("| Model | mean | median | P90 | use_nlos | use_temporal | use_crowd | use_prediction |")
    a("|---|---|---|---|---|---|---|---|")
    for k, v in res["ablations"].items():
        cf = v["config"]
        a(f"| {k} | {v['mean']:.2f} | {v['median']:.2f} | {v['p90']:.2f} | {cf['use_nlos']} | {cf['use_temporal']} | {cf['use_crowd']} | {cf['use_prediction']} |")
    a("")
    a("## Dropout (all anchors missing for 1-10 steps): error at the end of the outage (m)")
    a("")
    a("| steps | hold last | B3 EKF | neural state | neural forecast head |")
    a("|---|---|---|---|---|")
    for Ls in sorted(int(k) for k in res["dropout"]):
        d = res["dropout"][str(Ls)]
        a(f"| {Ls} | {d['hold_last_last']:.2f} | {d['ekf_b3_last']:.2f} | {d['nn_state[default]_last']:.2f} | {d.get('nn_forecast_last', float('nan')):.2f} |")
    a("")
    a("## Runtime")
    if bench:
        a(f"Python onnxruntime CPU ({bench['processor']}): size {bench['model_size_bytes'] / 1024:.0f} KB, session create {bench['cold_session_create_ms']:.0f} ms, "
          f"median {bench['latency_ms']['median']:.2f} ms, P95 {bench['latency_ms']['p95']:.2f} ms per step. Targets met (Python CPU): {bench['meets_targets']}.")
    if browser:
        for b in browser:
            j = json.loads(b.read_text())
            a(f"Browser ({j['environment'][:60]}...): cold load {j['cold_load_ms']:.0f} ms, median {j['warm_latency_ms']['median']:.2f} ms, P95 {j['warm_latency_ms']['p95']:.2f} ms.")
    else:
        a("**Browser (Chrome / Edge) numbers have not been measured yet.** Open `bench.html` and save the JSON as `reports/benchmark_browser_<browser>.json`, then re-run `make report`.")
    a("")
    a("## Limitations and failure modes")
    a("- Synthetic data only; real radio behaviour (multipath, body shadowing, antenna patterns) is not modelled. A pilot is the next step.")
    a("- Accuracy falls sharply with only 3 active anchors and with few valid anchors (see slices); the model cannot invent missing geometry.")
    a("- Heavy NLOS (more than about half of readings blocked) limits every method; stand-in hospital layouts are deliberately harsh.")
    a("- sigma is a learned estimate; use the calibration plot before treating it as a probability region.")
    a("- Dead-reckoning during long outages drifts; the forecast head only extends 10 steps (5 s).")
    a("- The optional crowd input is a proxy in this stand-in data (computed from jittered truth); do not trust crowd-benefit claims until A's crowd data and a deployment-faithful input exist.")
    a("- The clinic venue was never seen and never evaluated here; Member C scores it once after the freeze.")
    a("")
    a("## Reproduce")
    a("`make all` (see README). Seeds: train data 1000, dev data 2000, model seed 0; all manifests are written beside outputs.")
    Path("MODEL_CARD.md").write_text("\n".join(L) + "\n")
    print("wrote MODEL_CARD.md")


if __name__ == "__main__":
    main()
